"""GUI internationalisation (en / zh-Hans / zh-Hant).

Language resolution priority (contract v5, sections 1.1 / 1.4):

    CLI ``--lang`` > ``DISKINFER_LANG`` > ``LC_ALL`` / ``LANG`` >
    Qt ``QLocale.system().name()`` > ``en``

``zh``-prefixed tags map to ``zh-Hant`` when they carry Hant/TW/HK/MO and to
``zh-Hans`` otherwise.  Simplified-Chinese source strings are the dictionary
keys; a missing key falls back to the source text (the GUI never crashes).

Public API::

    detect() -> str                 # language implied by env + Qt locale
    set_lang(tag) -> str            # set current language ("auto" = detect)
    current() -> str                # "en" | "zh-Hans" | "zh-Hant"
    normalize_tag(tag) -> str|None  # zh_TW -> zh-Hant, en-US -> en, ...
    tr(key) -> str                  # translate to the current language
"""

from __future__ import annotations

import os
import re

SUPPORTED = ("en", "zh-Hans", "zh-Hant")
DEFAULT = "en"

_current = None

_HANT_RE = re.compile(r"(Hant|TW|HK|MO)", re.IGNORECASE)


def normalize_tag(tag):
    """Map a language tag (zh, zh-CN, zh_TW, en-US, auto, ...) to one of ours."""
    if not tag:
        return None
    tag = str(tag).strip().replace("_", "-")
    if not tag:
        return None
    low = tag.lower()
    if low == "auto":
        return "auto"
    if low == "zh" or low.startswith("zh-"):
        return "zh-Hant" if _HANT_RE.search(tag) else "zh-Hans"
    if low == "en" or low.startswith("en-"):
        return "en"
    return None


def _env_tag():
    for var in ("DISKINFER_LANG", "LC_ALL", "LANG", "LC_MESSAGES"):
        norm = normalize_tag(os.environ.get(var))
        if norm and norm != "auto":
            return norm
    return None


def _qt_tag():
    try:
        from PySide6.QtCore import QLocale  # lazily: i18n must import without Qt
    except Exception:
        return None
    try:
        return normalize_tag(QLocale.system().name())
    except Exception:
        return None


def detect() -> str:
    """Language from the environment, then the Qt locale, then English."""
    return _env_tag() or _qt_tag() or DEFAULT


def set_lang(tag=None) -> str:
    """Set the current language; ``None``/``auto`` re-detect it."""
    global _current
    norm = normalize_tag(tag) if tag is not None else None
    if norm == "auto" or norm is None:
        norm = detect()
    _current = norm
    return _current


def current() -> str:
    return _current or set_lang(detect())


def tr(key: str) -> str:
    """Translate ``key`` (a Simplified-Chinese source string) into the UI language."""
    lang = current()
    if lang == "zh-Hans":
        return key
    table = _EN if lang == "en" else _HANT
    return table.get(key, key)


def known_keys() -> list:
    """All source strings with translations (used by the GUI self tests)."""
    return sorted(set(_EN) | set(_HANT))


